cuts = []

def save(vid, folder, name, start, end, scene, sound=None):
    assert 0 <= start < end
    m['cut'](A / 'источники' / (vid + '.mp3'), folder, start, end)
    m['card'](folder, name, m['info'](vid), start, end, scene, sound)
    p = folder / 'описание.md'
    body = p.read_text(encoding='utf-8')
    body = body.replace('Название, автор и таймкод взяты из метаданных источника. Автоматическая вырезка следует границам авторской разметки; перед монтажом прослушать начало и конец.', 'Название сверено с подписью в кадре или сопоставлением исходной записи. Границы уточнены по паузам аудио; это вырезка из указанного ролика.')
    body += f'\nТочные границы в исходнике: **{start:.6f}–{end:.6f} с**.\n'
    p.write_text(body, encoding='utf-8')
    cuts.append({'source':vid, 'name':name, 'start':start, 'end':end, 'folder':str(folder.relative_to(A))})

